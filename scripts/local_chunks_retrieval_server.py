"""Serve local JSONL chunks through a RAGFlow-like retrieval API.

The server reads chunk records generated by ``rag_chunk/chunk_pdf.py``, embeds
them with the OpenAI-compatible embedding settings from ``eval-cfg.yaml``, and
returns cosine top-k chunks at ``POST /api/v1/retrieval``.
"""

from __future__ import annotations

import argparse
import json
import logging
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from typing import Any

import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from rag_eval_pipeline.config import load_config  # noqa: E402
from rag_eval_pipeline.local_retrieval import (  # noqa: E402
    LocalChunkRetriever,
    OpenAIEmbeddingClient,
    load_or_build_index,
    local_retrieval_settings,
    retrieval_response,
)


LOG_FORMAT = "%(asctime)s %(levelname)s %(name)s - %(message)s"
LOGGER = logging.getLogger("rag_eval.local_retrieval_server")


def make_handler(retriever: LocalChunkRetriever) -> type[BaseHTTPRequestHandler]:
    class LocalRetrievalHandler(BaseHTTPRequestHandler):
        server_version = "RagEvalLocalChunksRetrieval/0.1"

        def do_GET(self) -> None:  # noqa: N802
            self.write_json(
                {
                    "service": "rag-eval local chunks retrieval",
                    "status": "ok",
                    "endpoint": "POST /api/v1/retrieval",
                    "chunks": len(retriever.index),
                }
            )

        def do_POST(self) -> None:  # noqa: N802
            if self.path.rstrip("/") != "/api/v1/retrieval":
                self.write_json({"code": 404, "message": "not found"}, status=404)
                return

            try:
                body = self.rfile.read(int(self.headers.get("Content-Length", "0") or "0"))
                payload = json.loads(body.decode("utf-8")) if body else {}
            except json.JSONDecodeError as exc:
                self.write_json({"code": 400, "message": f"invalid JSON: {exc}"}, status=400)
                return

            question = str(payload.get("question") or payload.get("query") or "").strip()
            page_size = int(payload.get("page_size") or payload.get("top_k") or 5)
            similarity_threshold = float(payload.get("similarity_threshold") or 0.0)
            try:
                chunks = retriever.retrieve(
                    question,
                    page_size=page_size,
                    similarity_threshold=similarity_threshold,
                )
                self.write_json(retrieval_response(chunks))
            except Exception as exc:  # noqa: BLE001 - turn retrieval failures into JSON.
                LOGGER.exception("Retrieval failed")
                self.write_json({"code": 500, "message": str(exc)}, status=500)

        def log_message(self, format: str, *args: Any) -> None:
            LOGGER.info("%s - %s", self.address_string(), format % args)

        def write_json(self, payload: dict[str, Any], status: int = 200) -> None:
            body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
            self.send_response(status)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

    return LocalRetrievalHandler


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=ROOT / "scripts" / "eval-cfg.yaml")
    parser.add_argument("--chunks", type=Path, help="Override local_retrieval.chunks_path.")
    parser.add_argument("--cache", type=Path, help="Override local_retrieval.cache_path.")
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=9380)
    parser.add_argument("--rebuild-index", action="store_true", help="Recompute chunk embeddings even if cache exists.")
    parser.add_argument("--log-level", default="INFO")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    logging.basicConfig(
        level=getattr(logging, args.log_level.upper(), logging.INFO),
        format=LOG_FORMAT,
        datefmt="%Y-%m-%d %H:%M:%S",
        force=True,
    )

    config = load_config(args.config)
    settings = local_retrieval_settings(config, ROOT)
    if args.chunks:
        settings["chunks_path"] = args.chunks
    if args.cache:
        settings["cache_path"] = args.cache
    if args.rebuild_index:
        settings["rebuild"] = True

    required = ("embedding_base_url", "embedding_api_key", "embedding_model")
    missing = [name for name in required if not settings.get(name)]
    if missing:
        raise ValueError(
            "Missing embedding settings: "
            + ", ".join(missing)
            + ". Fill evaluation.embedding_* in the config or the referenced env vars."
        )

    embedding_client = OpenAIEmbeddingClient(
        base_url=str(settings["embedding_base_url"]),
        api_key=str(settings["embedding_api_key"]),
        model=str(settings["embedding_model"]),
        timeout=int(settings["timeout"]),
        retries=int(settings["retries"]),
    )
    index = load_or_build_index(
        chunks_path=settings["chunks_path"],
        cache_path=settings["cache_path"],
        embedding_client=embedding_client,
        embedding_model=str(settings["embedding_model"]),
        rebuild=bool(settings["rebuild"]),
        batch_size=int(settings["batch_size"]),
    )
    retriever = LocalChunkRetriever(index, embedding_client)
    server = ThreadingHTTPServer((args.host, args.port), make_handler(retriever))
    LOGGER.info("Local chunks retrieval listening on http://%s:%s/api/v1/retrieval", args.host, args.port)
    LOGGER.info("Chunks path: %s", settings["chunks_path"])
    LOGGER.info("Index cache: %s", settings["cache_path"])
    server.serve_forever()


if __name__ == "__main__":
    main()
